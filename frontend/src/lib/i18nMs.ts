/** Malay for a piece of screen or server text, or null when there is none. */
export function msFor(text: string, depth = 0): string | null {
  const exact = FB_MS[text];
  if (exact !== undefined) return exact;
  if (depth > 3) return null;
  const tr: Translate = (part) => msFor(part, depth + 1) ?? part;
  for (const [pattern, render] of FB_MS_PATTERNS) {
    const match = pattern.exec(text);
    if (match) return render(match, tr);
  }
  return null;
}
