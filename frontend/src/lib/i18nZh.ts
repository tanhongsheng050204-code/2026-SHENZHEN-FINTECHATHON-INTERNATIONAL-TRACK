/** Chinese for a piece of screen or server text, or null when there is none. */
export function zhFor(text: string, depth = 0): string | null {
  const exact = FB_ZH[text];
  if (exact !== undefined) return exact;
  if (depth > 3) return null;
  const tr: Translate = (part) => zhFor(part, depth + 1) ?? part;
  for (const [pattern, render] of FB_ZH_PATTERNS) {
    const match = pattern.exec(text);
    if (match) return render(match, tr);
  }
  return null;
}
